def results_paths(mode: str = "real") -> dict:
    if mode not in MODES:
        raise ValueError("mode must be one of " + str(MODES))
    d = RESULTS_DIR / mode
    return {
        "dir": str(d),
        "raw": str(d / "raw_results.jsonl"),
        "scored": str(d / "scored.csv"),
        "charts": str(d / "charts"),
        "meta": str(d / "run_meta.json"),
        "failures": str(d / "failures_to_label.csv"),
        "report": str(d / "Trust_Bench_Audit.pdf"),
    }


